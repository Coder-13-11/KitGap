// Copies db/migrations/*.sql into src/server/db/migrations-bundle.ts so the
// SQL ships inside the server bundle (the demo builds sandboxes from it at
// runtime, and serverless hosts don't include loose files by default).
// Runs automatically before dev, build and test.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "db", "migrations");
const entries = readdirSync(dir)
  .filter((file) => file.endsWith(".sql"))
  .sort()
  .map((name) => ({ name, sql: readFileSync(path.join(dir, name), "utf8") }));

const body = `// Generated by scripts/bundle-migrations.ts from db/migrations. Do not edit.
export const MIGRATION_FILES: { name: string; sql: string }[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(path.join(process.cwd(), "src", "server", "db", "migrations-bundle.ts"), body);
console.log(`Bundled ${entries.length} migration(s).`);
